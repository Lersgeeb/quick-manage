export const getLocaleForLanguage = (language: Language) => language === 'es' ? 'es-ES' : 'en-US';

export const translate = (language: Language, key: string, params?: TranslationParams) => {
  const value = translations[language][key] ?? translations.en[key] ?? key;

  if (typeof value === 'function') {
    return value(params);
  }

  if (!params) {
    return value;
  }

  return Object.entries(params).reduce(
    (translatedValue, [paramKey, paramValue]) => translatedValue.replaceAll(`{{${paramKey}}}`, String(paramValue)),
    value
  );
};
